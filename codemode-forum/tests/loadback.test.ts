// The way back (docs/forum-seite-plan-2026-11-26.en.md, section 6, phase 8), against a real spaces-files: a saved
// document's file loaded as a new version, its sections matched by heading, the appendix left out, the person as
// author; an unchanged file loads nothing, a file too large is refused, and a run goes on from the person's text. A
// PDF of the workspace is offered as a download, nothing else is.
import test from "node:test";
import assert from "node:assert/strict";
import type { Snapshot } from "../server/hub.ts";
import { headOf, fullDoc, writeVersion, type Revision } from "../server/plandoc.ts";
import { parseSaved } from "../server/export.ts";
import { startServer } from "./stack.ts";
import { filesService } from "./support/files-service.ts";

const THREE = ["fake/alpha", "fake/beta", "fake/gamma"];
const BRIEF = "Plan an app that shows the starry sky at a time and place.";
let seq = 0;
// "around": the fake team of table A (tests/fakes.ts)
const room = () => `around-l${process.pid}-${seq++}`;
const post = async (url: string, path: string, body: unknown) => {
	const r = await fetch(url + path, { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify(body) });
	return { status: r.status, body: (await r.json()) as Record<string, any> };
};
const getJson = async (url: string, path: string) => (await (await fetch(url + path)).json()) as any;
async function until<T>(what: string, fn: () => Promise<T | null | undefined | false>, ms = 60_000): Promise<T> {
	for (const end = Date.now() + ms; ; ) {
		const v = await fn();
		if (v) return v;
		if (Date.now() > end) throw new Error(`timed out waiting for ${what}`);
		await new Promise((r) => setTimeout(r, 100));
	}
}

test("parseSaved: the title line and the appendix go, a heading in a fence stays text, text before the first heading is a section", () => {
	const md = "# The brief\n\nA word first.\n\n## Goal\n\nShow the sky.\n\n```md\n## not a heading\n```\n\n## Steps ##\n\n1. One.\n\n---\n\n<!-- appendix: generated by codemode-forum, not written by a model -->\n\n## Appendix\n\nRuns.\n";
	assert.deepEqual(parseSaved(md, "Introduction"), [
		{ title: "Introduction", text: "A word first." },
		{ title: "Goal", text: "Show the sky.\n\n```md\n## not a heading\n```" },
		{ title: "Steps", text: "1. One." },
	]);
	assert.deepEqual(parseSaved("# Only a title\n\n## A\n\nx\n", "Intro"), [{ title: "A", text: "x" }]);
});

test("a saved document loaded back: matched by heading, the appendix left out, and the run goes on from it", async (t) => {
	const f = await filesService();
	const srv = await startServer({ fakes: THREE });
	t.after(async () => { await srv.close(); await f.close(); });
	await srv.stack.sources({ env: f.env });
	const id = room(), agent = `room-${id}`, space = srv.stack.space;
	await until("the sources process to offer spaces-files", async () => (await getJson(srv.url, `/api/rooms/${id}/link`)).files);
	await f.must({ op: "agent", id: agent });
	await f.cmd({ op: "workspace", name: "sky" });
	await f.must({ op: "write", ws: "sky", path: "plan/needs.md", text: "# Needs\n" });
	await f.must({ op: "write", ws: "sky", path: "plan/chart.pdf", text: "%PDF-1.4\n%fake\n" });
	await f.must({ op: "grant", ws: "sky", path: ".", relation: "editor", agent });
	assert.equal((await post(srv.url, `/api/rooms/${id}/link`, { action: "link", project: { workspace: "sky", path: "plan" } })).status, 200);
	const { blockId } = (await post(srv.url, `/api/rooms/${id}/task`, { brief: BRIEF })).body;
	const d = { session: id, blockId, table: "A" };
	const txn = await space.createTransaction(30_000);
	await writeVersion(space, txn.id, 3600_000, d, { author: "M1", model: "fake/alpha" }, { changes: [{ title: "Goal", text: "Show the sky." }, { title: "Steps", text: "1. Catalogue." }, { title: "Risks", text: "None known." }] } satisfies Revision);
	await space.commit(txn.id);
	const load = () => post(srv.url, `/api/rooms/${id}/load/${blockId}`, { by: "Lea" });

	assert.match((await load()).body.error, /never saved/);
	assert.equal((await post(srv.url, `/api/rooms/${id}/save/${blockId}`, { id: "load-save-0001" })).body.save.fileVersion, 1);
	// nothing changed in the workspace: nothing is loaded
	assert.deepEqual((await load()).body, { ok: true, unchanged: true, fileVersion: 1 });
	assert.equal((await headOf(space, d))!.version, 1);

	// Lea edits the file in spaces-files: Goal changed, a section added before Steps, Risks removed, the appendix kept
	const file = Buffer.from((await f.must({ op: "read", ws: "sky", path: "plan/plan.md" })).base64, "base64").toString("utf8");
	const edited = file.replace("Show the sky.", "Show the sky at a time and place, says Lea.").replace("## Steps", "## Data\n\nThe Yale catalogue.\n\n## Steps").replace(/## Risks\n\nNone known\.\n\n/, "");
	assert.notEqual(edited, file);
	await f.must({ op: "write", ws: "sky", path: "plan/plan.md", text: edited });
	const got = await load();
	assert.equal(got.status, 200, JSON.stringify(got.body));
	assert.deepEqual(got.body, { ok: true, version: 2, fileVersion: 2, path: "plan/plan.md" });
	const doc = await fullDoc(space, (await headOf(space, d))!);
	assert.deepEqual(doc.sections.map((s) => [s.sectionId, s.title, s.text, s.model === "human" ? s.author : s.model]), [
		["s1", "Goal", "Show the sky at a time and place, says Lea.", "Lea"],
		[doc.sections[1]!.sectionId, "Data", "The Yale catalogue.", "Lea"],
		["s2", "Steps", "1. Catalogue.", "fake/alpha"],
	]);
	assert.ok(!doc.sections.some((s) => /appendix|codemode-forum/i.test(s.text)), "the appendix is not loaded");
	assert.ok(((await getJson(srv.url, `/api/rooms/${id}`)) as Snapshot).lines.some((l) => l.text === "Lea loaded sky/plan/plan.md (file version 2) as version 2 of table A"));
	// loaded again: the same file version, nothing; the next save writes on top of version 2, no conflict
	assert.equal((await load()).body.unchanged, true);
	assert.equal((await post(srv.url, `/api/rooms/${id}/save/${blockId}`, { id: "load-save-0002" })).body.save.fileVersion, 3);

	// a file too large is refused and loads nothing
	await f.must({ op: "write", ws: "sky", path: "plan/plan.md", text: `# Big\n\n## Huge\n\n${"x".repeat(200_000)}\n` });
	assert.match((await load()).body.error, /a document loaded back has at most/);
	assert.equal((await headOf(space, d))!.version, 2);
	// one with a section over its limit names it
	await f.must({ op: "write", ws: "sky", path: "plan/plan.md", text: `# Big\n\n## Huge\n\n${"x".repeat(30_000)}\n` });
	assert.match((await load()).body.error, /cannot be loaded: section "Huge" has 30000 bytes/);

	// a PDF of the folder is a download; a text is not
	const pdf = await fetch(`${srv.url}/api/rooms/${id}/download?path=${encodeURIComponent("project/chart.pdf")}`);
	assert.equal(pdf.status, 200);
	assert.deepEqual([pdf.headers.get("content-type"), pdf.headers.get("content-disposition")], ["application/pdf", 'attachment; filename="chart.pdf"']);
	assert.equal(await pdf.text(), "%PDF-1.4\n%fake\n");
	assert.match((await getJson(srv.url, `/api/rooms/${id}/download?path=${encodeURIComponent("project/needs.md")}`)).error, /is no pdf \(text\)/);

	// the run goes on from the person's text: a file in the workspace written by her, loaded, then a run at table A
	await f.must({ op: "write", ws: "sky", path: "plan/plan.md", text: edited.replace("says Lea.", "says Lea, from the file.") });
	assert.equal((await load()).body.version, 3);
	assert.equal((await post(srv.url, `/api/rooms/${id}/run`, { blockId, models: THREE, budgetTokens: 200_000, way: "turns", rounds: 1 })).status, 200);
	await until("a call with the document", async () => (await space.readAll({ type: "FakeCall", fields: { session: id } }, { limit: 200 })).some((e) => String((e.fields as { prompt?: string }).prompt ?? "").includes("says Lea, from the file.")));
	await post(srv.url, `/api/rooms/${id}/stop`, {});
});
