// Saving a room's documents into its project folder (docs/forum-seite-plan-2026-11-26.en.md, section 6, phase 7),
// against a real spaces-files (tests/support/files-service.ts): a save sent again is one file version; a sources
// process killed between drawing the operation ID and the write, and one killed after the write, each leave one
// version; a file changed or removed in the workspace is not overwritten and both texts come back; a new name writes
// a new file; a revoked editor is refused in words.
import test from "node:test";
import assert from "node:assert/strict";
import { existsSync, mkdtempSync } from "node:fs";
import { rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import type { Snapshot } from "../server/hub.ts";
import { writeVersion, type Revision } from "../server/plandoc.ts";
import { startServer } from "./stack.ts";
import { filesService } from "./support/files-service.ts";

const BRIEF = "Plan an app that shows the starry sky at a time and place.";
let seq = 0;
const room = () => `save-${process.pid}-${seq++}`;
const post = async (url: string, path: string, body: unknown) => {
	const r = await fetch(url + path, { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify(body) });
	return { status: r.status, body: (await r.json()) as Record<string, any> };
};
const getJson = async (url: string, path: string) => (await (await fetch(url + path)).json()) as any;
const snapshot = (url: string, id: string) => getJson(url, `/api/rooms/${id}`) as Promise<Snapshot>;
async function until<T>(what: string, fn: () => Promise<T | null | undefined | false>, ms = 40_000): Promise<T> {
	for (const end = Date.now() + ms; ; ) {
		const v = await fn();
		if (v) return v;
		if (Date.now() > end) throw new Error(`timed out waiting for ${what}`);
		await new Promise((r) => setTimeout(r, 100));
	}
}

test("a document saved to the project folder: one version however it is sent or cut off, a changed file never overwritten", async (t) => {
	const f = await filesService();
	const srv = await startServer({ fakes: ["fake/alpha", "fake/beta", "fake/gamma"] });
	const dir = mkdtempSync(join(tmpdir(), "fsave-"));
	t.after(async () => { await srv.close(); await f.close(); await rm(dir, { recursive: true, force: true }); });
	let sources = await srv.stack.sources({ env: f.env });
	const id = room(), agent = `room-${id}`, space = srv.stack.space;
	await until("the sources process to offer spaces-files", async () => (await getJson(srv.url, `/api/rooms/${id}/link`)).files);
	await f.must({ op: "agent", id: agent });
	await f.cmd({ op: "workspace", name: "sky" });
	await f.must({ op: "write", ws: "sky", path: "plan/needs.md", text: "# Needs\n" });
	await f.must({ op: "grant", ws: "sky", path: ".", relation: "editor", agent });
	assert.equal((await post(srv.url, `/api/rooms/${id}/link`, { action: "link", project: { workspace: "sky", path: "plan" } })).status, 200);
	assert.equal((await post(srv.url, `/api/rooms/${id}/task`, { brief: BRIEF })).status, 200);
	const blockId = (await snapshot(srv.url, id)).blocks[0]!.blockId;
	const write = async (r: Revision) => {
		const txn = await space.createTransaction(30_000);
		await writeVersion(space, txn.id, 3600_000, { session: id, blockId, table: "A" }, { author: "M1", model: "fake/alpha" }, r);
		await space.commit(txn.id);
	};
	const read = async (path: string) => { const r = await f.must({ op: "read", ws: "sky", path }); return { text: Buffer.from(r.base64, "base64").toString("utf8"), version: r.version as number }; };
	const save = (saveId: string, name?: string) => post(srv.url, `/api/rooms/${id}/save/${blockId}`, { id: saveId, ...(name ? { name } : {}) });

	assert.match((await save("save-before-doc")).body.error, /has no document yet/);
	await write({ changes: [{ title: "Goal", text: "Show the sky at a time and place." }, { title: "Steps", text: "1. Catalogue. 2. Projection." }] });

	// the first save writes plan.md new; the same ID again is answered with it
	const first = await save("save-first-0001");
	assert.equal(first.status, 200, JSON.stringify(first.body));
	assert.deepEqual([first.body.again, first.body.save.path, first.body.save.fileVersion, first.body.save.docVersion], [false, "plan/plan.md", 1, 1]);
	assert.deepEqual((await save("save-first-0001")).body, { ...first.body, again: true });
	const file1 = await read("plan/plan.md");
	assert.equal(file1.version, 1);
	assert.ok(file1.text.startsWith(`# ${BRIEF}\n\n## Goal\n\nShow the sky at a time and place.\n\n## Steps\n`), file1.text);
	assert.ok(file1.text.includes("<!-- appendix: generated by codemode-forum"));
	assert.deepEqual((await snapshot(srv.url, id)).blocks[0]!.saved, { ...(await snapshot(srv.url, id)).blocks[0]!.saved!, path: "plan/plan.md", fileVersion: 1, docVersion: 1, workspace: "sky" });

	// a newer version saved against the file's version 1
	await write({ changes: [{ sectionId: "s2", base: 1, text: "1. Catalogue. 2. Projection. 3. Comets." }] });
	assert.deepEqual([(await save("save-second-001")).body.save.fileVersion, (await read("plan/plan.md")).version], [2, 2]);

	// killed after drawing the operation ID, before the write: the next process writes it, once
	const before = join(dir, "save-before"), after = join(dir, "save-after");
	await write({ changes: [{ sectionId: "s1", base: 1, text: "Show the sky at any time and place." }] });
	await srv.stack.kill(sources);
	let held = await srv.stack.sources({ env: { ...f.env, FORUM_TEST: "1", FORUM_TEST_SAVE_PAUSE: before } });
	let pending = save("save-third-0001");
	await until("the operation ID to be drawn", async () => existsSync(before));
	await srv.stack.kill(held, "SIGKILL");
	sources = await srv.stack.sources({ env: f.env });
	let got = await pending;
	assert.equal(got.status, 200, JSON.stringify(got.body));
	assert.deepEqual([got.body.save.fileVersion, (await read("plan/plan.md")).version], [3, 3]);

	// killed after the write, before its answer: the same write again, answered from spaces-files' receipt
	await write({ changes: [{ sectionId: "s1", base: 2, text: "Show the sky at any time and any place." }] });
	await srv.stack.kill(sources);
	held = await srv.stack.sources({ env: { ...f.env, FORUM_TEST: "1", FORUM_TEST_SAVED_PAUSE: after } });
	pending = save("save-fourth-001");
	await until("the write to be made", async () => existsSync(after));
	assert.equal((await read("plan/plan.md")).version, 4);
	await srv.stack.kill(held, "SIGKILL");
	sources = await srv.stack.sources({ env: f.env });
	got = await pending;
	assert.equal(got.status, 200, JSON.stringify(got.body));
	assert.deepEqual([got.body.save.fileVersion, (await read("plan/plan.md")).version], [4, 4]);
	assert.equal((await space.readAll({ type: "PlanSave", fields: { session: id, blockId } }, { limit: 20 })).length, 4);

	// someone changed the file in the workspace: nothing is overwritten, both texts come back
	await f.must({ op: "write", ws: "sky", path: "plan/plan.md", text: "# Plan\n\nEdited by Lea in spaces-files.\n" });
	await write({ changes: [{ sectionId: "s2", base: 2, text: "1. Catalogue. 2. Projection. 3. Comets. 4. Asteroids." }] });
	const conflict = await save("save-conflict-1");
	assert.equal(conflict.status, 409);
	assert.deepEqual([conflict.body.conflict.path, conflict.body.conflict.version, conflict.body.conflict.text], ["plan/plan.md", 5, "# Plan\n\nEdited by Lea in spaces-files.\n"]);
	assert.ok(conflict.body.conflict.mine.includes("4. Asteroids."));
	assert.deepEqual(await read("plan/plan.md"), { text: "# Plan\n\nEdited by Lea in spaces-files.\n", version: 5 });
	assert.equal(await space.count({ type: "PreviewPart", fields: { session: id } }), 0);
	// saved under a new name instead: a file of its own; the next save without a name keeps that one
	const renamed = await save("save-renamed-01", "plan-v2");
	assert.deepEqual([renamed.status, renamed.body.save.path, renamed.body.save.fileVersion], [200, "plan/plan-v2.md", 1]);
	assert.match((await read("plan/plan-v2.md")).text, /4\. Asteroids\./);
	assert.match((await save("save-bad-name-1", ".env")).body.error, /does not begin with a dot/);

	// removed in the workspace since the last save: said so, nothing written
	await f.must({ op: "remove", ws: "sky", path: "plan/plan-v2.md" });
	await write({ changes: [{ sectionId: "s1", base: 3, text: "Show the sky." }] });
	const gone = await save("save-gone-00001");
	assert.deepEqual([gone.status, gone.body.conflict.gone, gone.body.conflict.text], [409, true, null]);

	// the owner takes editor back: refused in words
	await f.must({ op: "revoke", ws: "sky", path: ".", relation: "editor", agent });
	const refused = await save("save-revoked-01", "other");
	assert.equal(refused.status, 400);
	assert.match(refused.body.error, /cannot see it|may not do that/);
	const lines = (await snapshot(srv.url, id)).lines.map((l) => l.text).filter((l) => / saved version /.test(l));
	assert.equal(lines.length, 5, lines.join("\n"));
});

test("a room set to save on acceptance saves the accepted version by itself, once", async (t) => {
	const f = await filesService();
	const srv = await startServer({ fakes: ["fake/alpha", "fake/beta", "fake/gamma"] });
	t.after(async () => { await srv.close(); await f.close(); });
	await srv.stack.sources({ env: f.env });
	const id = room(), agent = `room-${id}`, space = srv.stack.space;
	await until("the sources process to offer spaces-files", async () => (await getJson(srv.url, `/api/rooms/${id}/link`)).files);
	await f.must({ op: "agent", id: agent });
	await f.cmd({ op: "workspace", name: "sky" });
	await f.must({ op: "write", ws: "sky", path: "plan/needs.md", text: "# Needs\n" });
	await f.must({ op: "grant", ws: "sky", path: ".", relation: "editor", agent });
	assert.equal((await post(srv.url, `/api/rooms/${id}/link`, { action: "link", project: { workspace: "sky", path: "plan" } })).status, 200);
	assert.equal((await post(srv.url, `/api/rooms/${id}/task`, { brief: BRIEF })).status, 200);
	const blockId = (await snapshot(srv.url, id)).blocks[0]!.blockId;
	const txn = await space.createTransaction(30_000);
	await writeVersion(space, txn.id, 3600_000, { session: id, blockId, table: "A" }, { author: "M1", model: "fake/alpha" }, { changes: [{ title: "Goal", text: "Show the sky." }] });
	await space.commit(txn.id);
	// off by default: an acceptance saves nothing
	assert.equal((await post(srv.url, `/api/rooms/${id}/accept`, { blockId, version: 1, table: "A" })).status, 200);
	await new Promise((r) => setTimeout(r, 1500));
	assert.equal(await space.count({ type: "PlanSave", fields: { session: id } }), 0);
	assert.equal((await post(srv.url, `/api/rooms/${id}/settings`, { saveOnAccept: true })).status, 200);
	assert.equal((await getJson(srv.url, `/api/rooms/${id}`)).defaults.saveOnAccept, true);
	const t2 = await space.createTransaction(30_000);
	await writeVersion(space, t2.id, 3600_000, { session: id, blockId, table: "A" }, { author: "M2", model: "fake/beta" }, { changes: [{ sectionId: "s1", base: 1, text: "Show the sky, with comets." }] });
	await space.commit(t2.id);
	assert.equal((await post(srv.url, `/api/rooms/${id}/accept`, { blockId, version: 2, table: "A" })).status, 200);
	const saved = await until("the save on acceptance", async () => { const l = (await space.readAll({ type: "PlanSave", fields: { session: id } }, { limit: 5 })).map((e) => e.fields as { by: string; docVersion: number; fileVersion: number; path: string }); return l.length ? l : null; });
	assert.deepEqual(saved.map((x) => [x.by, x.docVersion, x.fileVersion, x.path]), [["FORUM (on acceptance)", 2, 1, "plan/plan.md"]]);
	const file = await f.must({ op: "read", ws: "sky", path: "plan/plan.md" });
	assert.match(Buffer.from(file.base64, "base64").toString("utf8"), /with comets/);
});
